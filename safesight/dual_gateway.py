"""SafeSight dual TPU model transport: same-frame YOLOv8n + SafetyVision.

Runs two remote JPEG gateways; no local model fallback. A pair is merged ONLY
when both TPU results refer to the exact same Frame (sequence + generation).
Never overlays a later/earlier SafetyVision result on the wrong evidence JPEG.
Single inference thread owns both Pika connections, but preview remains separate.
"""
from __future__ import annotations

from dataclasses import replace
import json
import math
import os
import time
from typing import Optional

from .jpeg_gateway import JPEGGatewayClient, JPEGSettings
from .logic import Detection

# Exact labels generated by the SafetyVision decoder; never absent-object checks.
SV_LABELS = frozenset({
    'fall_detected', 'gloves', 'goggles', 'hardhat', 'mask',
    'no_gloves', 'no_goggles', 'no_helmet', 'no_mask',
    'no_safety_vest', 'no_harness', 'safety_vest',
})


class PrefixedMetrics:
    """Prevent second TPU requests from inflating the first detector's FPS/RTT."""
    def __init__(self, parent, prefix='sv_'):
        self.parent, self.prefix = parent, prefix

    def observe(self, name, value):
        self.parent.observe(self.prefix + name, value)

    def tick(self, name, count=1):
        self.parent.tick(self.prefix + name, count)


class SVGatewayClient(JPEGGatewayClient):
    """Uses the existing JPEG transport but decodes SafetyVision labels."""
    name = 'SafetyVision v2 / LinQ TPU'

    def _on_response(self, channel, method, properties, body):
        task_id = self._task_id(properties)
        request = self.pending.pop(task_id, None)
        if request is None:
            self.metrics.tick('responses_unmatched')
            return
        received = self.clock()
        self.metrics.tick('responses_received')
        self.metrics.observe('rpc_round_trip', (received - request['sent']) * 1000)
        frame = request['frame']
        if (request['timed_out'] or received - frame.captured_at > self.settings.max_result_age
                or frame.sequence <= self.last_accepted):
            self.metrics.tick('responses_stale')
            return
        try:
            if len(body) > 262144:
                raise ValueError('oversized response')
            payload = json.loads(body.decode('utf-8'))
            if not isinstance(payload, dict) or payload.get('ok') is not True:
                raise ValueError('SV gateway returned error')
            height, width = frame.image.shape[:2]
            if (payload.get('frame_id') != task_id or payload.get('source_width') != width
                    or payload.get('source_height') != height):
                raise ValueError('mismatched frame / reply')
            raw = payload.get('detections')
            if not isinstance(raw, list) or len(raw) > 200:
                raise ValueError('bad detection list')
            detections = []
            for item in raw:
                if not isinstance(item, dict):
                    raise ValueError('invalid item')
                label = item.get('class_name')
                if label not in SV_LABELS:
                    raise ValueError('unknown SV label')
                score = item.get('confidence')
                box = item.get('bbox')
                if (isinstance(score, bool) or not isinstance(score, (int, float))
                        or not math.isfinite(score) or not 0 <= score <= 1
                        or not isinstance(box, list) or len(box) != 4
                        or any(isinstance(v, bool) or not isinstance(v, (int, float))
                               or not math.isfinite(v) for v in box)):
                    raise ValueError('bad confidence or bounding box')
                x1, y1, x2, y2 = [int(round(v)) for v in box]
                # The remote SV NMS may round a near-edge box to a zero-size one.
                if not (0 <= x1 < x2 <= width and 0 <= y1 < y2 <= height):
                    raise ValueError('out-of-frame bounding box')
                detections.append(Detection(label, float(score), (x1, y1, x2, y2)))
            stats = payload.get('stats', {})
            if isinstance(stats, dict):
                for name, field in (('gateway_cloud', 'gateway_total_ms'), ('gateway_tpu', 'tpu_worker_ms')):
                    val = stats.get(field)
                    if isinstance(val, (int, float)) and not isinstance(val, bool) and math.isfinite(val) and val >= 0:
                        self.metrics.observe(name, val)
            self.last_accepted = frame.sequence
            self.metrics.observe('capture_to_detection', (received - frame.captured_at) * 1000)
            self.metrics.tick('detections')
            self.last_error = None
            self.completed.append((frame, detections, task_id))
        except (TypeError, ValueError, KeyError, OverflowError):
            # Do not pass cloud exception text or paths to the public UI.
            self.last_error = 'Invalid SafetyVision response; inspect SV Gateway logs'
            self.metrics.tick('responses_invalid')


class DualGatewayClient:
    """Facade matching JPEGGatewayClient's connect/submit/poll/status/close.

    YOLO result remains authoritative for every person/zone detection.
    When SV and YOLO respond for the SAME submitted frame, outputs are joined.
    If SV is slow, emit YOLO-only after join_grace; NEVER attach a late SV
    reply to some other frame. With SV down, base detector keeps functioning.
    """
    name = 'LinQ TPU: YOLOv8n + SafetyVision v2'

    def __init__(self, settings: JPEGSettings, metrics, clock=time.perf_counter,
                 primary=None, secondary=None):
        sv_route = os.getenv('LINQ_SV_ROUTE', '').strip()
        if not sv_route or sv_route == settings.route:
            raise ValueError('LINQ_SV_ROUTE must match the DIFFERENT SafetyVision GATEWAY READY route')
        quality = int(os.getenv('LINQ_SV_JPEG_QUALITY', '75'))
        fps = float(os.getenv('LINQ_SV_MAX_REQUEST_FPS', '1.5'))
        sv_settings = replace(settings, route=sv_route, jpeg_quality=quality,
                              max_request_fps=fps)
        sv_settings.validate()
        self.clock = clock
        self.metrics = metrics
        self.max_result_age = settings.max_result_age
        self.join_grace = float(os.getenv('LINQ_SV_JOIN_GRACE', '0.70'))
        if not 0 <= self.join_grace <= self.max_result_age:
            raise ValueError('LINQ_SV_JOIN_GRACE must be in [0,LINQ_MAX_RESULT_AGE] seconds')
        self.primary = primary if primary is not None else JPEGGatewayClient(settings, metrics, clock=clock)
        self.secondary = secondary if secondary is not None else SVGatewayClient(sv_settings, PrefixedMetrics(metrics), clock=clock)
        self.sv_enabled = False
        self.sv_error: Optional[str] = None
        self.sv_joined = 0
        self.sv_missed = 0
        self.frames = {}  # (generation, seq) -> {frame, primary, sv, sent_sv, primary_at}
        self.last_accepted = (0, 0)

    def _disable_secondary(self, error):
        if self.secondary is not None:
            try:
                self.secondary.close()
            except Exception:
                pass
        self.sv_enabled = False
        self.sv_error = f'{type(error).__name__}; SV disabled until Web restart'
        # Do not discard primary jobs already submitted before the SV failure.

    def connect(self):
        self.primary.connect()  # Fail visibly if base path cannot connect.
        try:
            self.secondary.connect()
            self.sv_enabled = True
            self.sv_error = None
        except Exception as exc:
            self._disable_secondary(exc)  # Keep YOLO available.

    def can_submit(self):
        return self.primary.can_submit() and len(self.frames) < 3

    def submit(self, frame):
        if not self.can_submit():
            return False
        if not self.primary.submit(frame):
            return False
        key = (frame.generation, frame.sequence)
        state = {'frame': frame, 'primary': None, 'sv': None,
                 'sent_sv': False, 'primary_at': None, 'created': self.clock()}
        self.frames[key] = state
        if self.sv_enabled and self.secondary.can_submit():
            try:
                state['sent_sv'] = bool(self.secondary.submit(frame))
            except Exception as exc:
                self._disable_secondary(exc)
        return True

    def poll(self):
        # Receive from both independent RabbitMQ response queues, nonblocking.
        primaries = self.primary.poll()
        for frame, detections, task_id in primaries:
            key = (frame.generation, frame.sequence)
            state = self.frames.get(key)
            if state is not None:
                state['primary'] = (frame, detections, task_id)
                state['primary_at'] = self.clock()
        if self.sv_enabled:
            try:
                secondaries = self.secondary.poll()
                for frame, detections, _ in secondaries:
                    state = self.frames.get((frame.generation, frame.sequence))
                    if state is not None and state['sent_sv']:
                        state['sv'] = detections
            except Exception as exc:
                self._disable_secondary(exc)
        now = self.clock()
        merged = []
        # Dict preserves submission order; no results emitted twice.
        for key, state in list(self.frames.items()):
            if key <= self.last_accepted or now - state['frame'].captured_at > self.max_result_age:
                del self.frames[key]
                self.metrics.tick('dual_results_stale')
                continue
            primary = state['primary']
            if primary is not None:
                ready = (not state['sent_sv'] or not self.sv_enabled or state['sv'] is not None
                         or now - state['primary_at'] >= self.join_grace)
                if ready:
                    frame, detections, task_id = primary
                    if state['sv'] is not None:
                        detections = detections + state['sv']
                        self.sv_joined += 1
                        self.metrics.tick('sv_frames_joined')
                    elif state['sent_sv']:
                        self.sv_missed += 1
                        self.metrics.tick('sv_frames_not_joined')
                    frame = replace(frame, safetyvision_observed=state['sv'] is not None)
                    merged.append((frame, detections, task_id))
                    self.last_accepted = key
                    del self.frames[key]
                else:
                    # A newer primary-only reply must not overtake a pending
                    # same-frame SV join and invalidate its safety evidence.
                    break
            elif now - state['created'] > 5:
                # Primary either timed out or was rejected as stale.
                del self.frames[key]
            else:
                break
        return merged

    def status(self):
        base = self.primary.status()
        sv = self.secondary.status() if self.sv_enabled else {}
        return {**base,
                'inflight': base.get('inflight', 0) + sv.get('inflight', 0),
                'sv_enabled': self.sv_enabled,
                'sv_error': self.sv_error or sv.get('error'),
                'sv_joined': self.sv_joined,
                'sv_missed': self.sv_missed,
                'sv_inflight': sv.get('inflight', 0),
                'sv_route_ready': self.sv_enabled,
                'sv_request_fps': sv.get('max_request_fps'),
                }

    def close(self):
        self.primary.close()
        try:
            self.secondary.close()
        except Exception:
            pass
